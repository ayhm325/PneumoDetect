// ===============================================
// Security: تسجيل مركزي للأحداث الحساسة (Audit Logging)
// ===============================================
// هذا الملف مسؤول عن:
// 1. تسجيل كل الأحداث أو العمليات الحساسة في ملف audit.log
// 2. تضمين بيانات مثل: توقيت الحدث، المستخدم، IP، وتفاصيل إضافية
// 3. ضمان إنشاء مجلد السجلات إذا لم يكن موجوداً
// 4. التعامل مع الأخطاء بطريقة آمنة دون تعطيل التطبيق

// ===============================================
// استيرادات
import fs from "fs";           // للتعامل مع الملفات بشكل متزامن
import path from "path";       // لإدارة المسارات بين الأنظمة

// تحديد مسار ملف السجلات audit.log داخل مجلد logs
const LOG_PATH = path.resolve(process.cwd(), "logs", "audit.log");

// ===============================================
// الدالة الأساسية لتسجيل حدث حساس
// يُرسل لها كائن يحتوي على:
// event  : اسم الحدث أو نوع العملية
// userId : معرف المستخدم المتسبب في الحدث
// ip     : عنوان IP للمستخدم
// details: أي بيانات إضافية مرتبطة بالحدث
export function logAudit({ event, userId, ip, details }) {
  // إنشاء مدخل سجل بصيغة JSON
  const entry = {
    timestamp: new Date().toISOString(), // توقيت الحدث ISO
    event,
    userId,
    ip,
    details,
  };

  try {
    // ===============================================
    // التأكد من أن مجلد logs موجود لتجنب خطأ ENOENT
    const dir = path.dirname(LOG_PATH);
    try {
      fs.mkdirSync(dir, { recursive: true }); // إنشاء المجلد إذا لم يكن موجود
    } catch (mkdirErr) {
      // إذا فشل إنشاء المجلد، نتجاهله لأن appendFileSync سيلقي الخطأ
    }

    // كتابة المدخل في الملف (append) مع فصل كل مدخل بسطر جديد
    fs.appendFileSync(LOG_PATH, JSON.stringify(entry) + "\n");
  } catch (err) {
    // في الإنتاج يفضل استخدام خدمة تسجيل احترافية
    // هنا نكتفي بطباعة الخطأ على الكونسول لتجنب تعطيل التطبيق
    console.error("Audit log error:", err);
  }
}

