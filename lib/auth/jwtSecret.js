// ===============================================
// إدارة السرّ (Secret) المستخدم لتوقيع والتحقق من JWT
// ===============================================
// هذا الملف مسؤول عن:
// - جلب قيمة JWT_SECRET من متغيرات البيئة
// - فرض قواعد أمان صارمة في بيئة الإنتاج
// - السماح بتسهيلات مؤقتة فقط أثناء التطوير أو الاختبار

// ===============================================
// قيمة افتراضية غير آمنة ❌
// تُستخدم فقط في بيئة التطوير أو الاختبار
// ⚠️ لا يجب الاعتماد عليها في الإنتاج أبداً
const DEV_FALLBACK = "dev-only-insecure-secret-change-me";

// ===============================================
// دالة جلب السر الخاص بالـ JWT
export function getJwtSecret() {
  // قراءة السر من متغير البيئة JWT_SECRET
  const secret = process.env.JWT_SECRET;

  // التحقق هل التطبيق يعمل في وضع الإنتاج
  const isProd = process.env.NODE_ENV === "production";

  // -----------------------------------------------
  // الحالة 1: السر موجود وطوله 32 حرف أو أكثر
  // هذا يعتبر آمن، فنقوم بإرجاعه مباشرة
  if (secret && String(secret).length >= 32) {
    return secret;
  }

  // -----------------------------------------------
  // الحالة 2: نحن في بيئة الإنتاج
  // ❌ لا يُسمح إطلاقاً بالعمل بدون JWT_SECRET قوي
  if (isProd) {
    throw new Error(
      "JWT_SECRET is required in production and must be at least 32 characters."
    );
  }

  // -----------------------------------------------
  // الحالة 3: بيئة تطوير أو اختبار
  // ✔️ يسمح باستخدام سر قصير أو حتى عدم وجوده
  // في حال عدم وجوده، نرجع القيمة الافتراضية DEV_FALLBACK
  return secret || DEV_FALLBACK;
}

// ===============================================
// ملاحظات أمنية مهمة:
// - JWT_SECRET هو المفتاح الأساسي لأمان التوكنات.
// - أي شخص يحصل عليه يستطيع تزوير JWT.
// - في الإنتاج: يجب أن يكون طويلاً (>= 32 حرف) وعشوائياً.
// - يفضّل توليده باستخدام أدوات توليد أسرار قوية.
// - وجود fallback مسموح فقط لتسهيل التطوير المحلي.
// ===============================================
