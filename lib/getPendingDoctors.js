import prisma from "./prismaClient.js"; // عميل Prisma للتعامل مع قاعدة البيانات

/**
 * جلب جميع الأطباء الذين لديهم حالة "active"
 * ويشمل بيانات المستخدم المرتبط بكل طبيب (user)
 * ويتم ترتيبهم حسب تاريخ الإنشاء تصاعديًا
 * 
 * @returns {Promise<Array>} مصفوفة من الأطباء مع بيانات المستخدم المرتبط
 */
export async function getAvailableDoctors() {
  return await prisma.doctor.findMany({
    where: {
      status: "active", // فقط الأطباء النشطون
    },
    include: {
      user: true, // جلب بيانات المستخدم المرتبطة بكل طبيب
    },
    orderBy: {
      createdAt: "asc", // ترتيب حسب تاريخ الإنشاء
    },
  });
}

